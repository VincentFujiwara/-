//
//Даны две переменные вещественного типа: A, B.
//Перераспределить значения данных переменных так,
//чтобы в A оказалось меньшее из значений,
//а в B — большее. Вывести новые значения переменных A и B.
// 
// Решение Урсу Артёма

#include <stdio.h>
int main (){
	double a,b;
	scanf("%lf %lf",&a,&b);
	if (a>b){
		printf ("%lf\n",a);
			printf ("%lf",b);
	}
	else {
		printf ("%lf\n",b);
			printf ("%lf",a);
	}
	
	return 0;
}
