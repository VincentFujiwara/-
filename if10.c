//
//Даны две переменные целого типа: A и B. Если их значения не равны,
//то присвоить каждой переменной сумму этих значений, а если равны,
//то присвоить переменным нулевые значения. Вывести новые значения
//переменных A и B.
// 
// Решение Урсу Артёма

#include <stdio.h>
int main (){
	int a,b;
	scanf("%d %d",&a,&b);
	if (a==b){
		a=0;
		b=0;
		printf ("%d\n",a);
		printf ("%d",b);
	}
	else {
		printf ("%d\n",a+b);
	}
	
	return 0;
}
